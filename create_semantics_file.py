import pandas as pd
import re

# Создаем шаблон Excel файла с готовой семантикой
# Структура: Кластер | Подкластер | Ключевая фраза | Частотность | Гео | Статус очистки

data = {
    'Кластер': [],
    'Подкластер': [],
    'Ключевая фраза': [],
    'Частотность': [],
    'Гео': [],
    'Статус очистки': []
}

df = pd.DataFrame(data)

# Сохраняем в Excel файл
output_file = 'semantics_ready.xlsx'
df.to_excel(output_file, index=False, sheet_name='Семантика')

print(f"Файл {output_file} успешно создан!")
print("Структура файла:")
print("- Кластер: тематическая группа")
print("- Подкластер: уточненная группа")
print("- Ключевая фраза: поисковый запрос")
print("- Частотность: количество запросов в месяц")
print("- Гео: географическая привязка")
print("- Статус очистки: сохранен/удален и причина")
